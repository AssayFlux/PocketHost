package com.assayflux.pockethost.diagnostics

import android.content.Context
import android.net.Uri
import android.os.Build
import org.json.JSONArray
import org.json.JSONObject
import java.time.Instant
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

/**
 * Creates a user-initiated, privacy-conscious support archive.
 * It deliberately excludes tunnel tokens, project files, IP addresses,
 * account identifiers and other credentials.
 */
object DiagnosticsBundle {
    fun export(context: Context, destination: Uri): Boolean = runCatching {
        val output = context.contentResolver.openOutputStream(destination)
            ?: error("Cannot open the selected diagnostics destination.")
        val preferences = context.getSharedPreferences("pockethost_state", Context.MODE_PRIVATE)
        val metrics = MetricsStore.snapshot(context)
        val packageInfo = context.packageManager.getPackageInfo(context.packageName, 0)

        ZipOutputStream(output).use { zip ->
            val device = JSONObject()
                .put("generatedAt", Instant.now().toString())
                .put("appVersion", packageInfo.versionName ?: "unknown")
                .put("sdkInt", Build.VERSION.SDK_INT)
                .put("androidRelease", Build.VERSION.RELEASE ?: "unknown")
                .put("supportedAbis", JSONArray(Build.SUPPORTED_ABIS.toList()))
                .put("deviceModel", Build.MODEL ?: "unknown")
                .put("manufacturer", Build.MANUFACTURER ?: "unknown")
            putText(zip, "device.json", device.toString(2))

            val configuration = JSONObject()
                .put("staticPort", preferences.getInt("port", 8080))
                .put("pythonPort", preferences.getInt("python_port", 8081))
                .put("lanAccessEnabled", preferences.getBoolean("allow_lan", false))
                .put("pythonEnabled", preferences.getBoolean("python_enabled", false))
                .put("tunnelEnabled", preferences.getBoolean("tunnel_enabled", false))
                .put("keepCpuAwake", preferences.getBoolean("keep_awake", false))
                .put("serviceStatus", preferences.getString("service_status", "unknown") ?: "unknown")
            putText(zip, "configuration.json", configuration.toString(2))

            val traffic = JSONObject()
                .put("totalRequests", metrics.totalRequests)
                .put("totalBytes", metrics.totalBytes)
                .put("todayRequests", metrics.todayRequests)
                .put("todayBytes", metrics.todayBytes)
            putText(zip, "traffic.json", traffic.toString(2))

            OperationalLog.appendArchivesToZip(context, zip)
            putText(
                zip,
                "README.txt",
                "AssayFlux PocketHost diagnostics bundle\n" +
                    "Generated by an explicit user export.\n" +
                    "Contains app version, Android compatibility metadata, non-secret hosting settings, " +
                    "traffic aggregates and redacted operational logs.\n" +
                    "Does not contain website/Python project files or the Cloudflare tunnel token.\n" +
                    "Review this archive before sharing it with anyone. Device model/manufacturer and " +
                    "Android version are included to help diagnose compatibility issues.\n"
            )
        }
        true
    }.getOrDefault(false)

    private fun putText(zip: ZipOutputStream, name: String, value: String) {
        zip.putNextEntry(ZipEntry(name))
        zip.write(value.toByteArray(Charsets.UTF_8))
        zip.closeEntry()
    }
}
